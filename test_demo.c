/* Interactive Demo - Calculator with All Operations */

int main() {
    int num1;
    int num2;
    int result;

    read(num1);
    read(num2);

    result = num1 + num2;
    print(result);

    result = num1 - num2;
    print(result);

    result = num1 * num2;
    print(result);

    result = num1 / num2;
    print(result);

    return 0;
}
